class AsianPaint{

    String brand;
    double volume;
    String type;
    boolean isGlossy;
    int paintId;
    double price;
    String color;
    int coverage; 
    boolean isWaterProof;
    String finish;

  public AsianPaint(String brand, double volume, String type, boolean isGlossy, int paintId, double price, String color, int coverage, boolean isWaterProof, String finish) {
        this.brand = brand;
        this.volume = volume;
        this.type = type;
        this.isGlossy = isGlossy;
        this.paintId = paintId;
        this.price = price;
        this.color = color;
        this.coverage = coverage;
        this.isWaterProof = isWaterProof;
        this.finish = finish;
    }

}