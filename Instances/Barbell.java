class Barbell{

String brand;
double weight;
String material;
boolean isAdjustable;
int barbellId;
double price;
String type;
int maxLoad;
boolean hasKnurling;
String color;

public Barbell(String brand,double weight,String material,boolean isAdjustable,int barbellId,double price,String type,int maxLoad,boolean hasKnurling,String color){
    this.brand=brand;
    this.weight=weight;
    this.material=material;
    this.isAdjustable=isAdjustable;
    this.barbellId=barbellId;
    this.price=price;
    this.type=type;
    this.maxLoad=maxLoad;
    this.hasKnurling=hasKnurling;
    this.color=color;
}

}