class Stump{

String material;
double height;
double diameter;
String color;
double weight;
boolean isWooden;
boolean isPainted;
int stumpNumber;
boolean hasLogo;
String brand;

 public Stump(String material,double height,double diameter,String color,double weight,boolean isWooden,boolean isPainted,int stumpNumber,boolean hasLogo,String brand){
	 
	 this.material=material;
	 this.height=height;
	 this.diameter=diameter;
	 this.color=color;
	 this.weight=weight;
	 this.isWooden=isWooden;
	 this.isPainted=isPainted;
	 this.stumpNumber=stumpNumber;
	 this.hasLogo=hasLogo;
	 this.brand=brand;
	 
 }
 }