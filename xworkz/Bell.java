class Bell{
    String brand;
    double weight;
    String material;
    boolean isAdjustable;
    int bellId;
    double price;
    String type;
    int maxVolume;
    boolean hasHandle;
    String color;
	
 public Bell(String brand,double weight,String material,boolean isAdjustable,int bellId,double price,String type,int maxVolume,boolean hasHandle,String color){
        this.brand=brand;
        this.weight=weight;
        this.material=material;
        this.isAdjustable=isAdjustable;
        this.bellId=bellId;
        this.price=price;
        this.type=type;
        this.maxVolume=maxVolume;
        this.hasHandle=hasHandle;
        this.color=color;
    }
}