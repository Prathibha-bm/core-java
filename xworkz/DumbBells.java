class DumbBells{

String brand;
double weight;
String material;
boolean isAdjustable;
int setId;
double price;
String type;
int quantity;
boolean hasGrip;
String color;

public DumbBells(String brand,double weight,String material,boolean isAdjustable,int setId,double price,String type,int quantity,boolean hasGrip,String color){
    this.brand=brand;
    this.weight=weight;
    this.material=material;
    this.isAdjustable=isAdjustable;
    this.setId=setId;
    this.price=price;
    this.type=type;
    this.quantity=quantity;
    this.hasGrip=hasGrip;
    this.color=color;
}

}