class LED{
	public static void main(String[] args){
		byte brightnessLevel = 10; 
		System.out.println(brightnessLevel)	;	
		short manufacturingYear = 2023;
		System.out.println(manufacturingYear);
		int price = 800; 
		System.out.println(price)	;	
		long serialNumber = 112233445566L;
		System.out.println(serialNumber);
		float powerConsumption = 9.5f;  
		System.out.println(powerConsumption);
		double weight = 0.450;
		System.out.println(weight);
		char lightColor = 'W'; 
		System.out.println(lightColor);
	}
}