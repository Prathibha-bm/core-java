class Rock{
    String name;
    double weight;
    String type;
    boolean isIgneous;
    int rockId;
    double price;
    String color;
    int hardness;
    boolean isPolished;
    String origin;
    public Rock(String name,double weight,String type,boolean isIgneous,int rockId,double price,String color,int hardness,boolean isPolished,String origin){
        this.name=name;
        this.weight=weight;
        this.type=type;
        this.isIgneous=isIgneous;
        this.rockId=rockId;
        this.price=price;
        this.color=color;
        this.hardness=hardness;
        this.isPolished=isPolished;
        this.origin=origin;
    }
}